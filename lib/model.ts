// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds every
// rankable pre-token protocol below the watchlist floor: the early rows the radar exists to find. A
// protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id, no
// symbol); the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board. They do a second job here: they price the model.
//
// Implied value follows only from the snapshot's own figures, in four factors:
//
//   category multiple = what the market already pays per dollar of TVL for protocols in the same
//                         category. For each category, the median mcap/TVL of its live-token protocols
//                         (at least 3 comparables); a category with fewer borrows the global median.
//                         Blended 75/25 with the global median and clamped to [0.05, 1.50], so no
//                         thin category can set an absurd price. This is the model's anchor: a lending
//                         protocol is priced like lending protocols that already trade, not like a DEX.
//   growth     = clamp(change_7d, -50, 150) per cent; growthMult = 1 + growth/100 x 0.6
//   maturity   = 0.55 + min(age_days, 1095) / 1095 x 0.45   (age_days unknown: 365)
//                Age is the time since DefiLlama first listed the protocol: how long it has run with
//                no token on record. Older, still pre-token protocols have survived longer without
//                launching, which is what the radar is for.
//   breadth    = 1 + 0.02 x min(max(chains - 1, 0), 5)   (1.00 to 1.10)
//                A protocol live on more chains reaches more farmers.
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturityMult x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// prints the category multiples with their comparable counts so the reader can check the anchor.

